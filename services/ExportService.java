package services;

import interfaces.Exportable;
import model.Balance;
import model.Expense;
import model.ExpenseSplit;
import model.Roommate;
import model.User;
import utils.FileUtils;
import utils.StringUtils;

import java.io.*;
import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.List;

/**
 * Service for exporting expense reports.
 * 
 * This class demonstrates:
 * - PrintWriter for formatted text output
 * - StringBuffer for efficient string building
 * - File I/O operations
 * - Export functionality
 * - Report generation
 * 
 * Syllabus Topics Covered:
 * - PrintWriter for formatted output
 * - StringBuffer for mutable string building
 * - String vs StringBuffer comparison
 * - File I/O (FileWriter, PrintWriter)
 * - try-with-resources for resource management
 * - IOException handling
 * - Export functionality
 * - Report formatting
 * 
 * @see java.io.PrintWriter
 * @see java.io.StringWriter
 * @see java.lang.StringBuffer
 * @see utils.FileUtils
 */
public class ExportService {
    
    private static final DateTimeFormatter DATE_FORMATTER = DateTimeFormatter.ofPattern("dd MMM yyyy");
    private static final DateTimeFormatter DATETIME_FORMATTER = DateTimeFormatter.ofPattern("dd MMM yyyy HH:mm:ss");
    
    /**
     * Exports a complete expense report to a text file.
     * 
     * This method demonstrates:
     * - PrintWriter for formatted output
     * - StringBuffer for efficient report building
     * - String vs StringBuffer comparison
     * - Proper resource management with try-with-resources
     * - Exception handling
     * 
     * Syllabus Topics:
     * - PrintWriter
     * - StringBuffer vs String
     * - File I/O
     * - Exception handling
     * - Resource management
     * 
     * @param currentUser the logged-in user
     * @param roommates list of roommates
     * @param expenses list of expenses
     * @param balances list of balances
     * @return the exported file
     * @throws IOException if export fails
     */
    public File exportExpenseReport(User currentUser, List<Roommate> roommates, 
                                    List<Expense> expenses, List<model.Balance> balances) throws IOException {
        
        File exportFile = FileUtils.createExportFile(
            FileUtils.generateTimestampedFilename("expense_report", "txt"));
        
        // Demonstrate StringBuffer vs String for report building
        // StringBuffer is used for efficient string building
        StringBuffer report = new StringBuffer();
        
        buildReportHeader(report, currentUser);
        buildRoommateSection(report, roommates);
        buildExpenseSection(report, expenses);
        buildBalanceSection(report, balances);
        buildFooter(report);
        
        // Write using PrintWriter for formatted output
        try (PrintWriter writer = new PrintWriter(new FileWriter(exportFile, StandardCharsets.UTF_8))) {
            writer.write(report.toString());
        }
        
        return exportFile;
    }
    
    /**
     * Builds the report header.
     * 
     * Demonstrates: StringBuffer.append(), String formatting
     * 
     * @param report the StringBuffer to append to
     * @param currentUser the current user
     */
    private void buildReportHeader(StringBuffer report, User currentUser) {
        report.append("================================================================================\n");
        report.append("                    EXPENSESPLITTERAPP - EXPENSE REPORT\n");
        report.append("================================================================================\n\n");
        
        report.append("Generated on: ").append(LocalDateTime.now().format(DateTimeFormatter.ofPattern("dd MMM yyyy HH:mm:ss"))).append("\n");
        report.append("Generated by: ").append(currentUser != null ? currentUser.getUsername() : "Unknown").append("\n");
        report.append("Report type: Complete Expense Report\n");
        report.append("\n");
        report.append("================================================================================\n\n");
    }
    
    /**
     * Builds the roommate section.
     * 
     * Demonstrates: StringBuffer operations, iteration
     */
    private void buildRoommateSection(StringBuffer report, List<Roommate> roommates) {
        report.append("ROOMMATES\n");
        report.append("--------------------------------------------------------------------------------\n");
        
        if (roommates == null || roommates.isEmpty()) {
            report.append("No roommates found.\n\n");
            return;
        }
        
        report.append(String.format("%-5s %-30s %-20s %-20s\n", "ID", "Name", "Phone", "UPI ID"));
        report.append("--------------------------------------------------------------------------------\n");
        
        for (Roommate r : roommates) {
            report.append(String.format("%-5d %-30s %-20s %-20s\n",
                r.getMemberId(),
                StringUtils.formatDescription(r.getName(), 30),
                r.getPhone() != null ? r.getPhone() : "-",
                r.getUpiId() != null ? r.getUpiId() : "-"));
        }
        report.append("\n");
    }
    
    /**
     * Builds the expense section with splits.
     * 
     * Demonstrates: StringBuffer, nested iteration, formatting
     */
    private void buildExpenseSection(StringBuffer report, List<Expense> expenses) {
        report.append("EXPENSES\n");
        report.append("--------------------------------------------------------------------------------\n");
        
        if (expenses == null || expenses.isEmpty()) {
            report.append("No expenses recorded.\n\n");
            return;
        }
        
        report.append(String.format("%-5s %-12s %-30s %-20s %-12s %s\n", 
            "ID", "Date", "Description", "Payer", "Amount", "Splits"));
        report.append("--------------------------------------------------------------------------------\n");
        
        for (Expense e : expenses) {
            report.append(String.format("%-5d %-12s %-30s %-20s %-12s\n",
                e.getExpenseId(),
                e.getExpenseDate().format(DATE_FORMATTER),
                StringUtils.formatDescription(e.getDescription(), 30),
                StringUtils.formatDescription(e.getPayerName(), 20),
                StringUtils.formatCurrency(e.getTotalAmount())));
            
            // Add splits
            if (e.getSplits() != null && !e.getSplits().isEmpty()) {
                for (ExpenseSplit split : e.getSplits()) {
                    report.append(String.format("       -> %s: %s (%s)\n",
                        split.getMemberName(),
                        StringUtils.formatCurrency(split.getShareAmount()),
                        split.isSettled() ? "SETTLED" : "PENDING"));
                }
            }
        }
        report.append("\n");
    }
    
    /**
     * Builds the balance summary section.
     */
    private void buildBalanceSection(StringBuffer report, List<model.Balance> balances) {
        report.append("BALANCE SUMMARY\n");
        report.append("--------------------------------------------------------------------------------\n");
        
        if (balances == null || balances.isEmpty()) {
            report.append("No balance data available.\n\n");
            return;
        }
        
        report.append(String.format("%-5s %-30s %-15s %-15s %-15s %s\n",
            "ID", "Member", "Total Paid", "Total Owed", "Net Balance", "Status"));
        report.append("--------------------------------------------------------------------------------\n");
        
        BigDecimal totalPaid = BigDecimal.ZERO;
        BigDecimal totalOwed = BigDecimal.ZERO;
        
        for (model.Balance b : balances) {
            report.append(String.format("%-5d %-30s %-15s %-15s %-15s %s\n",
                b.getMemberId(),
                StringUtils.formatDescription(b.getMemberName(), 30),
                StringUtils.formatCurrency(b.getTotalPaid()),
                StringUtils.formatCurrency(b.getTotalOwed()),
                StringUtils.formatCurrency(b.getNetBalance()),
                b.getStatus()));
            
            totalPaid = totalPaid.add(b.getTotalPaid());
            totalOwed = totalOwed.add(b.getTotalOwed());
        }
        
        report.append("--------------------------------------------------------------------------------\n");
        report.append(String.format("TOTALS: %45s %15s %15s\n",
            StringUtils.formatCurrency(totalPaid),
            StringUtils.formatCurrency(totalOwed),
            StringUtils.formatCurrency(totalPaid.subtract(totalOwed))));
        report.append("\n");
    }
    
    /**
     * Builds the report footer.
     */
    private void buildFooter(StringBuffer report) {
        report.append("================================================================================\n");
        report.append("End of Report\n");
        report.append("Generated by ExpenseSplitterApp\n");
        report.append("================================================================================\n");
    }
    
    /**
     * Exports a simple summary report.
     * 
     * Demonstrates: Quick export with minimal data
     * 
     * @param expenses list of expenses
     * @return the exported file
     * @throws IOException if export fails
     */
    public File exportSimpleSummary(List<Expense> expenses) throws IOException {
        File exportFile = FileUtils.createExportFile(
            FileUtils.generateTimestampedFilename("expense_summary", "txt"));
        
        StringBuffer report = new StringBuffer();
        report.append("EXPENSE SUMMARY\n");
        report.append("Generated: ").append(LocalDateTime.now().format(DATETIME_FORMATTER)).append("\n\n");
        
        if (expenses == null || expenses.isEmpty()) {
            report.append("No expenses to report.\n");
        } else {
            BigDecimal total = BigDecimal.ZERO;
            for (Expense e : expenses) {
                report.append(String.format("%s | %s | %s | %s\n",
                    e.getExpenseDate().format(DATE_FORMATTER),
                    StringUtils.formatDescription(e.getDescription(), 40),
                    StringUtils.formatCurrency(e.getTotalAmount()),
                    e.getPayerName()));
                total = total.add(e.getTotalAmount());
            }
            report.append("\nTotal: ").append(StringUtils.formatCurrency(total));
        }
        
        try (PrintWriter writer = new PrintWriter(new FileWriter(exportFile, StandardCharsets.UTF_8))) {
            writer.write(report.toString());
        }
        
        return exportFile;
    }
    
    /**
     * Demonstrates String vs StringBuffer performance.
     * 
     * This method shows the difference between String concatenation
     * and StringBuffer for building large strings.
     * 
     * @param iterations number of iterations
     * @return time comparison string
     */
    public String demonstrateStringVsStringBuffer(int iterations) {
        // Using String concatenation (inefficient)
        long startString = System.nanoTime();
        String str = "";
        for (int i = 0; i < iterations; i++) {
            str += "Item " + i + "\n";
        }
        long stringTime = System.nanoTime() - startString;
        
        // Using StringBuffer (efficient)
        long startBuffer = System.nanoTime();
        StringBuffer buffer = new StringBuffer();
        for (int i = 0; i < iterations; i++) {
            buffer.append("Item ").append(i).append("\n");
        }
        long bufferTime = System.nanoTime() - startBuffer;
        
        return String.format("String concatenation: %.2f ms\nStringBuffer: %.2f ms\nSpeedup: %.1fx",
            stringTime / 1_000_000.0, bufferTime / 1_000_000.0, 
            (double) stringTime / bufferTime);
    }
}